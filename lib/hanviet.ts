/**
 * Lấy âm Hán Việt của một ký tự chữ Hán đơn lẻ
 */
export function getSingleKanjiHanViet(char: string): string | null {
  return KANJI_HANVIET_MAP[char] || null;
}

/**
 * Kiểm tra xem một ký tự có phải là chữ Hán (Kanji) hay không
 */
export function isKanji(char: string): boolean {
  return /[\u4e00-\u9faf\u3400-\u4dbf]/.test(char);
}

/**
 * Trả về âm Hán Việt cho một từ hoặc cụm từ tiếng Nhật
 * Ví dụ:
 * - "消費" => "TIÊU PHÍ"
 * - "消費期限" => "TIÊU PHÍ KỲ HẠN"
 * - "緑" => "LỤC"
 * - "親しい" => "THÂN"
 * - "配る" => "PHỐI"
 * - "坂をのぼる" => "PHẢN"
 */
export function getHanViet(text: string): string {
  if (!text) return "";
  const chars = Array.from(text);
  const result: string[] = [];

  for (const c of chars) {
    if (isKanji(c)) {
      const hv = KANJI_HANVIET_MAP[c];
      if (hv) {
        result.push(hv);
      } else {
        result.push(c);
      }
    }
  }

  return result.join(" ");
}

/**
 * Phân tích chi tiết từng chữ Hán trong một từ
 * Ví dụ:
 * "消費" => [{ kanji: "消", hanViet: "TIÊU" }, { kanji: "費", hanViet: "PHÍ" }]
 */
export function getKanjiBreakdown(text: string): Array<{ kanji: string; hanViet: string }> {
  if (!text) return [];
  const chars = Array.from(text);
  const items: Array<{ kanji: string; hanViet: string }> = [];
  const seen = new Set<string>();

  for (const c of chars) {
    if (isKanji(c) && !seen.has(c)) {
      seen.add(c);
      const hv = KANJI_HANVIET_MAP[c] || "";
      items.push({ kanji: c, hanViet: hv });
    }
  }

  return items;
}

/**
 * Trích xuất từ khoá được hỏi trong câu hỏi trắc nghiệm
 * (Thường được bao quanh bởi __từ__, hoặc 【từ】, hoặc 「từ」)
 */
export function extractTestedTarget(questionText: string): string | null {
  if (!questionText) return null;
  const underscoreMatch = questionText.match(/__([^_]+)__/);
  if (underscoreMatch && underscoreMatch[1]) {
    return underscoreMatch[1].trim();
  }

  const bracketMatch = questionText.match(/【([^】]+)】/);
  if (bracketMatch && bracketMatch[1]) {
    return bracketMatch[1].trim();
  }

  const quoteMatch = questionText.match(/「([^」]+)」/);
  if (quoteMatch && quoteMatch[1]) {
    return quoteMatch[1].trim();
  }

  return null;
}

/**
 * Xác định từ khóa Kanji trọng tâm của câu hỏi
 * Bao gồm cả dạng kanji_reading (Kanji trong câu hỏi)
 * và dạng kanji_spelling (Hiragana trong câu hỏi, Kanji trong đáp án đúng)
 */
export function getQuestionKanjiTarget(question: {
  questionText: string;
  options: Array<{ id: string; text: string }>;
  correctOptionId?: string | null;
}): { targetJa: string; hanViet: string; breakdown: Array<{ kanji: string; hanViet: string }> } | null {
  const extracted = extractTestedTarget(question.questionText);
  
  // 1. Nếu từ được gạch chân có chứa Kanji
  if (extracted && /[\u4e00-\u9faf\u3400-\u4dbf]/.test(extracted)) {
    const hanViet = getHanViet(extracted);
    const breakdown = getKanjiBreakdown(extracted);
    return { targetJa: extracted, hanViet, breakdown };
  }

  // 2. Nếu từ được gạch chân là Hiragana (kanji_spelling), kiểm tra đáp án đúng
  const correctOpt = question.options.find(o => o.id === question.correctOptionId);
  if (correctOpt && /[\u4e00-\u9faf\u3400-\u4dbf]/.test(correctOpt.text)) {
    const hanViet = getHanViet(correctOpt.text);
    const breakdown = getKanjiBreakdown(correctOpt.text);
    return { targetJa: correctOpt.text, hanViet, breakdown };
  }

  // 3. Fallback: tìm bất kỳ Kanji nào trong từ trắc nghiệm hoặc đáp án đúng
  if (correctOpt) {
    const hanViet = getHanViet(correctOpt.text);
    if (hanViet) {
      return { targetJa: correctOpt.text, hanViet, breakdown: getKanjiBreakdown(correctOpt.text) };
    }
  }

  return null;
}
